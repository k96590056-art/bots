<script>
import ClickCaptcha from './libs/ClickCaptcha.vue';

export default {
  name: 'register',
  data() {
    return {
      imgLis: ['2PYL', '6AQ5', '8PHD', '21I7', '69HM', 'ACWA', 'DUZ7', 'IY98', 'K647', 'M52T', 'NY52', 'NZFA', 'SN76', 'SP4D', 'VAEO', 'YFQM', 'ZZU5', '7GQT', 'LFW3', 'NU2T', 'UAE3'],
      show: false,
      showCaptcha: false,
      pid: '',
      userName: '',
      passWord: '',
      confirmPass: '',
      realname: '',
      paypassword: '',
      userNameFocused: false,
      passWordFocused: false,
      confirmPassFocused: false,
      realnameFocused: false,
      paypasswordFocused: false,
      userNameError: false,
      passWordError: false,
      confirmPassError: false,
      realnameError: false,
      paypasswordError: false,
      userNameErrorMsg: '',
      passWordErrorMsg: '',
      confirmPassErrorMsg: '',
      realnameErrorMsg: '',
      paypasswordErrorMsg: '',
      passWordVisible: false,
      confirmPassVisible: false,
      paypasswordVisible: false,
      agreed: true,
    };
  },
  components: {
      ClickCaptcha
  },
  created() {
    let that = this;
    var query = that.$route.query;
    if (query.pid) {
      that.pid = query.pid;

    }
  },
  mounted() {
  },
  methods: {
    onFocus(field) {
      this[`${field}Focused`] = true;
      if (this[field] && this[field].trim() !== '') {
        this.validate(field);
      }
    },
    onBlur(field) {
      this[`${field}Focused`] = false;
      this.validate(field);
    },
    onInput(field) {
      if (this[field] && this[field].trim() !== '') {
        this.validate(field);
      } else {
        this[`${field}Error`] = false;
        this[`${field}ErrorMsg`] = '';
      }
    },
    validate(field) {
      if (field === 'userName') {
        if (!this.userName || this.userName.trim() === '') {
          this.userNameError = true;
          this.userNameErrorMsg = '用户名不能为空';
        } else {
          const namereg = /^(?![0-9]+$)(?![a-zA-Z]+$)[0-9A-Za-z]{6,}$/;
          if (!namereg.test(this.userName)) {
            this.userNameError = true;
            this.userNameErrorMsg = '用户名长度不得低于6位，以字母和数字组合！';
          } else {
            this.userNameError = false;
            this.userNameErrorMsg = '';
          }
        }
      }
      if (field === 'passWord') {
        if (!this.passWord || this.passWord.trim() === '') {
          this.passWordError = true;
          this.passWordErrorMsg = '密码不能为空';
        } else {
          const passwordreg = /^(?![0-9]+$)(?![a-zA-Z]+$)[0-9A-Za-z]{8,}$/;
          if (!passwordreg.test(this.passWord)) {
            this.passWordError = true;
            this.passWordErrorMsg = '密码长度最少8位！以字母和数字组合！';
          } else {
            this.passWordError = false;
            this.passWordErrorMsg = '';
          }
        }
      }
      if (field === 'confirmPass') {
        if (!this.confirmPass || this.confirmPass.trim() === '') {
          this.confirmPassError = true;
          this.confirmPassErrorMsg = '确认密码不能为空';
        } else if (this.confirmPass !== this.passWord) {
          this.confirmPassError = true;
          this.confirmPassErrorMsg = '两次密码不一致！';
        } else {
          this.confirmPassError = false;
          this.confirmPassErrorMsg = '';
        }
      }
      if (field === 'realname') {
        if (!this.realname || this.realname.trim() === '') {
          this.realnameError = true;
          this.realnameErrorMsg = '真实姓名不能为空';
        } else {
          const realnamereg = /^[\u0391-\uFFE5a-zA-Z·&\\s]+$/;
          if (!realnamereg.test(this.realname)) {
            this.realnameError = true;
            this.realnameErrorMsg = '姓名格式不正确，可以是中，英文名称！';
          } else {
            this.realnameError = false;
            this.realnameErrorMsg = '';
          }
        }
      }
      if (field === 'paypassword') {
        if (!this.paypassword || this.paypassword.trim() === '') {
          this.paypasswordError = true;
          this.paypasswordErrorMsg = '取款密码不能为空';
        } else {
          const paypasswordreg = /^.{6,6}$/;
          if (!paypasswordreg.test(this.paypassword)) {
            this.paypasswordError = true;
            this.paypasswordErrorMsg = '支付密码长度需是6位！';
          } else {
            this.paypasswordError = false;
            this.paypasswordErrorMsg = '';
          }
        }
      }
    },
    clearInput(field) {
      this[field] = '';
      this[`${field}Error`] = false;
      this[`${field}ErrorMsg`] = '';
    },
    togglePassword(field) {
      if (field === 'passWord') {
        this.passWordVisible = !this.passWordVisible;
      } else if (field === 'confirmPass') {
        this.confirmPassVisible = !this.confirmPassVisible;
      } else if (field === 'paypassword') {
        this.paypasswordVisible = !this.paypasswordVisible;
      }
    },
    openKefu() {
      let that = this;
      that.showTost('正在链接人工客服');
      that.$apiFun.post('/api/getservicerurl', {}).then(res => {
        console.log(res);
        if (res.code != 200) {
          that.showTost(res.message);
        }
        if (res.code == 200) {
          window.open(res.data.url, '_blank');
        }
      });
    },
    goNav(url) {
      let that = this;
      this.$router.push({ path: url });
    },
    login() {
      let that = this;

      // 验证所有字段
      that.validate('userName');
      that.validate('passWord');
      that.validate('confirmPass');
      that.validate('realname');
      that.validate('paypassword');

      // 检查是否有错误
      if (that.userNameError || that.passWordError || that.confirmPassError || that.realnameError || that.paypasswordError) {
        that.showTost('请检查输入信息');
        return;
      }

      // 检查是否同意条款
      if (!that.agreed) {
        that.showTost('请先同意相关条款和隐私政策');
        return;
      }

      this.showCaptcha = true;
    },
    onCaptchaSuccess(sessionId) {
        this.showCaptcha = false;
        this.doRegister(sessionId);
    },
    doRegister(sessionId) {
      let that = this;
      let info = {
        name: that.userName,
        password: that.passWord,
        confirmPass: that.confirmPass,
        realname: that.realname,
        paypassword: that.paypassword,
      };
      if (sessionId) {
        info.captcha_id = sessionId;
      }
      if (that.pid) {
        info.pid = that.pid;
      }
      that.show = true;
      that.$apiFun.register(info).then(res => {
        that.showTost(res.message);

        if (res.code == 200) {
          sessionStorage.setItem('token', res.data.api_token);
          that.$store.commit('changToken');

          that.getUserInfo();
        }
        that.show = false;
      });
    },
    showTost(title) {
      $('body').append(`
            <div class='ant-message' style='top: 400px;'><span><div class='ant-message-notice'><div class='ant-message-notice-content'>
            <div class='ant-message-custom-content ant-message-info'><span role='img' aria-label='info-circle' class='anticon anticon-info-circle'>
            <svg viewBox='64 64 896 896' focusable='false' data-icon='info-circle' width='1em' height='1em' fill='currentColor' aria-hidden='true'>
            <path d='M512 64C264.6 64 64 264.6 64 512s200.6 448 448 448 448-200.6 448-448S759.4 64 512 64zm32 664c0 4.4-3.6 8-8 8h-48c-4.4 0-8-3.6-8-8V456c0-4.4 3.6-8 8-8h48c4.4 0 8 3.6 8 8v272zm-32-344a48.01 48.01 0 010-96 48.01 48.01 0 010 96z'></path></svg></span><span>
            ${title}
            </span></div></div></div></span>
            </div>`);
      setTimeout('$(".ant-message").detach()', 2000);
    },
    getUserInfo() {
      let that = this;
      that.$apiFun.post('/api/user', {}).then(res => {
        if (res.code !== 200) {
          that.showTost(res.message);
          // that.changIndex(); // removed
        }
        if (res.code === 200) {
          let userInfo = res.data;
          let str = userInfo.current_vip;
          let index = str.indexOf('P');
          let vip = str.substr(index + 1, str.length); //04
          userInfo.vip = vip;
          localStorage.setItem('userInfo', JSON.stringify(userInfo));

          that.$store.commit('changUserInfo');
          that.goNav('/');
        }
      });
    },
  },
};
</script>

